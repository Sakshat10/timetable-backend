-- Teacher grade scope: lets a teacher-subject link be explicitly marked as able to teach EVERY grade, instead of requiring one
-- teacher_subject_grades row per grade per academic year.
--
-- Purely additive: one new enum type and one new column on "teacher_subjects". The column is NOT NULL with DEFAULT 'SELECTED_GRADES', so every
-- existing row (and every row written by code that does not know the column) gets exactly the behaviour it had before: eligible only for the grades
-- that have an explicit teacher_subject_grades row. PostgreSQL adds a column with a constant default without rewriting the table. No existing row,
-- constraint or index is changed, and "teacher_subject_grades" is untouched.
--
-- ROLLBACK (only if no link was set to ALL_GRADES, or if you accept those teachers losing their grade permission):
--   ALTER TABLE "teacher_subjects" DROP COLUMN "gradeScope";
--   DROP TYPE "GradeScope";
-- Roll the application code back FIRST (older code ignores the column). Dropping the column while links are ALL_GRADES silently turns them into
-- "selected grades with no rows", i.e. teachers who can no longer be assigned: list them first with
--   SELECT "id", "teacherId", "subjectId" FROM "teacher_subjects" WHERE "gradeScope" = 'ALL_GRADES';
-- and either add their grade rows or accept the loss. Existing assignments are never deleted by a rollback, but feasibility and generation would
-- then report them as ASSIGNED_TEACHER_NOT_ELIGIBLE / TEACHER_NOT_ELIGIBLE until the grade rows exist.
--
-- Generated by `prisma migrate diff`.

-- CreateEnum
CREATE TYPE "GradeScope" AS ENUM ('SELECTED_GRADES', 'ALL_GRADES');

-- AlterTable
ALTER TABLE "teacher_subjects" ADD COLUMN     "gradeScope" "GradeScope" NOT NULL DEFAULT 'SELECTED_GRADES';
