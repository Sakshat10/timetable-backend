-- Security (Phase 2): school setup tokens. The single-use credential that authorizes the FIRST admin of a school.
--
-- Purely additive: ONE new table with its indexes, foreign keys and CHECK constraints. No existing table, column, index or row is altered
-- or read, so schools and admins created before this migration are untouched (existing schools simply have no token row: they already have an
-- admin, and the operator-run recovery command can issue a token for any school that does not).
--
-- Only the SHA-256 hash of a token is stored ("tokenHash"); the raw token is shown once, when it is issued. At most one row per school
-- (UNIQUE "schoolId"): rotating a token replaces the row.
--
-- ROLLBACK: `DROP TABLE "school_setup_tokens";` (dependent objects are only this table's own indexes and the two foreign keys it owns).
-- Dropping it loses nothing else, but it discards any UNCONSUMED token: the first admin of a school that has not registered yet could then no
-- longer register, and the recovery command (which needs the table) would have to be run again after the migration is re-applied. Roll back the
-- application code first (older code ignores the table), and drop the table only afterwards. Consumed tokens are history only: registration
-- never needs them again.
--
-- Part 1 is generated by `prisma migrate diff`. Part 2 is hand-written: Prisma's schema language cannot express CHECK constraints.

-- ===== Part 1: generated =====

-- CreateTable
CREATE TABLE "school_setup_tokens" (
    "id" TEXT NOT NULL,
    "schoolId" TEXT NOT NULL,
    "tokenHash" TEXT NOT NULL,
    "expiresAt" TIMESTAMPTZ(3) NOT NULL,
    "consumedAt" TIMESTAMPTZ(3),
    "consumedByAdminId" TEXT,
    "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "school_setup_tokens_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE UNIQUE INDEX "school_setup_tokens_schoolId_key" ON "school_setup_tokens"("schoolId");

-- CreateIndex
CREATE UNIQUE INDEX "school_setup_tokens_tokenHash_key" ON "school_setup_tokens"("tokenHash");

-- CreateIndex
CREATE INDEX "school_setup_tokens_consumedByAdminId_idx" ON "school_setup_tokens"("consumedByAdminId");

-- AddForeignKey
ALTER TABLE "school_setup_tokens" ADD CONSTRAINT "school_setup_tokens_schoolId_fkey" FOREIGN KEY ("schoolId") REFERENCES "schools"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- AddForeignKey
ALTER TABLE "school_setup_tokens" ADD CONSTRAINT "school_setup_tokens_consumedByAdminId_fkey" FOREIGN KEY ("consumedByAdminId") REFERENCES "admins"("id") ON DELETE SET NULL ON UPDATE CASCADE;

-- ===== Part 2: hand-written constraints =====

-- A token always expires after it was issued.
ALTER TABLE "school_setup_tokens"
  ADD CONSTRAINT "school_setup_tokens_expiry_check" CHECK ("expiresAt" > "createdAt");

-- Consumption is coherent: it never precedes issuance, and a consuming admin is only recorded for a consumed token
-- ("consumedByAdminId" becomes NULL again if that admin is deleted, which the foreign key's ON DELETE SET NULL does).
ALTER TABLE "school_setup_tokens"
  ADD CONSTRAINT "school_setup_tokens_consumption_check" CHECK (
    ("consumedAt" IS NULL OR "consumedAt" >= "createdAt")
    AND ("consumedByAdminId" IS NULL OR "consumedAt" IS NOT NULL)
  );
